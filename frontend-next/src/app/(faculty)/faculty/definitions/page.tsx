"use client";

import * as React from "react";
import Box from "@mui/material/Box";
import Card from "@mui/material/Card";
import Stack from "@mui/material/Stack";
import Typography from "@mui/material/Typography";
import { useQuery } from "@tanstack/react-query";
import api from "@/lib/api";
import { PageHeader } from "@/components/ui/PageHeader";
import { DataState } from "@/components/ui/DataState";
import { ListSkeleton } from "@/components/ui/Skeletons";

interface Definition { id: string; title: string; where: string; summary: string; items: { term: string; rule: string }[] }

/** What every status word on the staff screens means. Generated by the server from the same numbers the screens use, so it cannot be out of date. */
export default function DefinitionsPage() {
  const query = useQuery<Definition[]>({ queryKey: ["faculty", "definitions"], queryFn: async () => (await api.get("/api/faculty/definitions")).data.data, staleTime: 60 * 60_000 });
  return (
    <>
      <PageHeader title="What the words mean" subtitle="Each word means one thing everywhere. If two screens use different words, they measure different things." />
      <DataState loading={query.isLoading} error={query.isError ? query.error : undefined} onRetry={() => query.refetch()} skeleton={<ListSkeleton rows={5} />}>
        <Stack spacing={2.5} sx={{ maxWidth: 820 }}>
          {(query.data ?? []).map((d) => (
            <Card key={d.id} variant="outlined" sx={{ borderColor: "outlineVariant", p: 2.5 }}>
              <Typography variant="subtitle1" fontWeight={600}>{d.title}</Typography>
              <Typography variant="caption" color="text.secondary">Used in: {d.where}</Typography>
              <Typography variant="body2" sx={{ my: 1.5 }}>{d.summary}</Typography>
              <Stack spacing={0.75}>
                {d.items.map((i) => (
                  <Box key={i.term} sx={{ display: "flex", gap: 2 }}>
                    <Typography variant="body2" fontWeight={600} sx={{ minWidth: 110 }}>{i.term}</Typography>
                    <Typography variant="body2" color="text.secondary">{i.rule}</Typography>
                  </Box>
                ))}
              </Stack>
            </Card>
          ))}
        </Stack>
      </DataState>
    </>
  );
}
